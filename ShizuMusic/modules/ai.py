# 🧠 100% PURE GEMINI ASYNC HELPERS 
# ==========================================
async def fetch_gemini_text(prompt, system_prompt=""):
    if not GEMINI_API_KEY:
        return "❌ **Error:** Gemini API Key Render par set nahi hai!"
    
    # 🎯 Updated to SUPERFAST gemini-1.5-flash
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={GEMINI_API_KEY}"
    full_prompt = f"{system_prompt}\n\nUser Request: {prompt}" if system_prompt else prompt
    data = {"contents": [{"parts": [{"text": full_prompt}]}]}
    
    try:
        async with aiohttp.ClientSession() as session:
            async with session.post(url, headers={'Content-Type': 'application/json'}, json=data) as resp:
                if resp.status == 200:
                    result = await resp.json()
                    if "candidates" in result:
                        return result["candidates"][0]["content"]["parts"][0]["text"]
                else:
                    return f"❌ **Google API Error:** {resp.status} - Request rejected by Gemini!"
    except Exception as e:
        return f"❌ **Error:** `{e}`"
    return "❌ **Unknown Error Occurred.**"

async def fetch_gemini_image(prompt):
    if not GEMINI_API_KEY:
        return None, "Gemini API Key missing!"
    
    # 🎯 Pure Gemini Imagen 3
    url = f"https://generativelanguage.googleapis.com/v1beta/models/imagen-3.0-generate-001:predict?key={GEMINI_API_KEY}"
    data = {
        "instances": [{"prompt": prompt}],
        "parameters": {"sampleCount": 1}
    }
    
    try:
        async with aiohttp.ClientSession() as session:
            async with session.post(url, headers={'Content-Type': 'application/json'}, json=data) as resp:
                if resp.status == 200:
                    result = await resp.json()
                    if "predictions" in result:
                        b64_img = result["predictions"][0]["bytesBase64Encoded"]
                        photo_bytes = base64.b64decode(b64_img)
                        photo_io = BytesIO(photo_bytes)
                        photo_io.name = "mgb_ai_image.jpg"
                        return photo_io, None
                else:
                    err = await resp.text()
                    return None, f"Google API Error ({resp.status}): Shayad prompt safety filters ne block kiya ya API limits cross hui."
    except Exception as e:
        return None, f"Exception: {e}"
    return None, "Unknown error generated by Google API"

