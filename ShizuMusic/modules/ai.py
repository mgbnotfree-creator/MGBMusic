# 1. 🤖 AI Chatbot (ChatGPT Style)
# ==========================================
@bot.on_message(filters.command(["ask", "ai", "chat"], prefixes=["/", "!", "."]))
async def ai_chat(client, message: Message):
    if len(message.command) < 2:
        return await message.reply_text("✨ **Boss, koi sawal pucho!**\nExample: `/ask Who is Elon Musk?`")
    
    query = message.text.split(None, 1)[1]
    encoded_query = urllib.parse.quote(query)
    
    system_prompt = urllib.parse.quote("You are a smart AI assistant created by MGB NOT FREE CODER. Answer politely and concisely.")
    api_url = f"https://text.pollinations.ai/{encoded_query}?system={system_prompt}"
    
    m = await message.reply_text("🔄 **MGB AI soch raha hai...**")
    
    try:
        async with aiohttp.ClientSession() as session:
            async with session.get(api_url) as resp:
                if resp.status == 200:
                    answer = await resp.text()
                    await m.edit_text(f"🤖 **MGB AI:**\n\n{answer}\n\n✨ _Powered by **MGB NOT FREE CODER**_")
                else:
                    await m.edit_text("❌ Server busy hai, thodi der baad try karein!")
    except Exception as e:
        await m.edit_text(f"Error: {e}")

